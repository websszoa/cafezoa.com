-- -----------------------------------------------------------------------------
-- 2. 구독 테이블
-- -----------------------------------------------------------------------------
create table if not exists public.subscriptions (
  id bigint generated by default as identity primary key,

  -- 소식을 받을 이메일 (같은 이메일은 한 번만 구독, 아래 고유 인덱스)
  email text not null
    check (
      char_length(email) <= 254
      and email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    ),

  status public.subscribe_status not null default 'active',

  -- 로그인 상태에서 구독한 경우만 회원과 연결합니다. 비로그인 구독은 null.
  -- 회원 탈퇴(프로필 삭제) 시에도 구독 기록은 남기고 연결만 끊습니다.
  user_id uuid references public.profiles (id) on delete set null,

  -- 설문 (화면에서는 나이대·경로가 필수지만, 설문을 건너뛰는 흐름도
  -- 지원할 수 있도록 DB에서는 비워 둘 수 있게 합니다)
  age_group public.subscribe_age_group,
  source public.subscribe_source,
  styles public.subscribe_style[] not null default '{}'
    check (cardinality(styles) <= 20),
  priorities public.subscribe_priority[] not null default '{}'
    check (cardinality(priorities) <= 20),
  wish text
    check (wish is null or char_length(btrim(wish)) <= 200),

  -- 개인정보 수집·이용 동의. 동의하지 않은 구독은 저장되지 않습니다.
  privacy_consent boolean not null check (privacy_consent = true),
  privacy_consented_at timestamptz not null default now(),

  -- 구독 해지 시각. 해지 상태일 때만 값이 있습니다.
  unsubscribed_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint subscriptions_unsubscribed_at_check check (
    (status = 'unsubscribed' and unsubscribed_at is not null)
    or (status = 'active' and unsubscribed_at is null)
  )
);

comment on table public.subscriptions is
