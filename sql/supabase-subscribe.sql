--     (enum 값 추가: alter type public.subscribe_style add value if not exists '새값';)
--
-- 보안 원칙
--   - RLS(Row Level Security)를 항상 활성화합니다.
--   - 로그인하지 않은 방문자(anon)도 구독할 수 있도록 INSERT만 허용합니다.
--     입력 가능한 컬럼만 권한을 주고, 구독 상태·해지 시각은 입력할 수 없습니다.
--   - 구독자 목록은 관리자만 조회·관리합니다. 로그인 사용자는 본인 구독만 조회합니다.
--   - anon에게는 SELECT 권한이 없으므로, 클라이언트에서 insert 후 .select()로
--     결과를 다시 읽지 마세요. (권한 오류)
--   - 같은 이메일은 한 번만 구독됩니다. 다시 신청하면 고유 제약 오류(23505)가
--     나므로 화면에서 "이미 구독 중인 이메일이에요"로 안내하세요.
--   - 구독 해지(메일의 해지 링크)와 삭제는 service_role(서버)에서 처리합니다.
--
-- Supabase Advisor 경고 방지 (supabase-support.sql과 같은 기준)
--   - 정책 안의 auth.uid()는 (select auth.uid())로 감싸 씁니다.
--   - 같은 역할·동작에 permissive 정책을 하나만 둡니다.
--   - INSERT 정책은 true가 아닌 실제 조건을 검사합니다.
--   - 외래 키(user_id)에는 인덱스를 둡니다.
--   - 새 함수를 만들지 않고 supabase-function.sql의 함수를 재사용합니다.
