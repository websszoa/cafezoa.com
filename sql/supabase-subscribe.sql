--   1단계: 이메일(필수), 개인정보 수집 동의(필수)
--   2단계 설문:
--     - 나이대(하나 선택)            ← lib/subscribe.ts subscribeAgeGroups
--     - 알게 된 경로(하나 선택)       ← lib/subscribe.ts subscribeSources
--     - 좋아하는 카페 스타일(복수 선택) ← lib/subscribe.ts subscribeStyles
