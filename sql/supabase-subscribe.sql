-- 같은 이메일 중복 구독 방지 (대소문자 구분 없이)
create unique index if not exists subscriptions_email_lower_key
  on public.subscriptions (lower(email));

-- 외래 키 인덱스 (본인 구독 조회, 회원 삭제 시 연결 해제에 사용)
create index if not exists subscriptions_user_id_idx
  on public.subscriptions (user_id);

-- -----------------------------------------------------------------------------
-- 3. updated_at 자동 갱신 (supabase-function.sql의 함수 재사용)
-- -----------------------------------------------------------------------------
drop trigger if exists subscriptions_set_updated_at on public.subscriptions;
create trigger subscriptions_set_updated_at
before update on public.subscriptions
for each row
execute function private.set_updated_at();

-- -----------------------------------------------------------------------------
-- 4. 권한 (컬럼 단위 최소 권한)
-- -----------------------------------------------------------------------------
alter table public.subscriptions enable row level security;

revoke all on table public.subscriptions from anon, authenticated;
revoke all on sequence public.subscriptions_id_seq from anon, authenticated;

-- 방문자·회원: 구독 폼 입력 컬럼만 INSERT 가능
-- (status, unsubscribed_at, 시각 컬럼은 기본값으로만 채워집니다)
grant insert (
  email,
  user_id,
  age_group,
  source,
  styles,
  priorities,
  wish,
  privacy_consent
) on table public.subscriptions to anon, authenticated;

-- 회원: 본인 구독 조회 / 관리자: 전체 조회 (행 범위는 아래 RLS 정책이 제한)
grant select on table public.subscriptions to authenticated;

-- 관리자: 구독 상태 관리 (해지 처리 등). 관리자 여부는 아래 RLS 정책이 확인
grant update (status, unsubscribed_at)
  on table public.subscriptions to authenticated;

-- -----------------------------------------------------------------------------
-- 5. RLS 정책
-- -----------------------------------------------------------------------------
-- 구독: 비로그인은 user_id 없이, 로그인은 본인 user_id로만 신청할 수 있습니다.
-- 신청 상태는 항상 active여야 합니다. (해지 상태로 위장 신청 방지)
drop policy if exists "subscriptions_insert_anyone" on public.subscriptions;
create policy "subscriptions_insert_anyone"
  on public.subscriptions
  for insert
  to anon, authenticated
  with check (
    status = 'active'
    and privacy_consent = true
    and (user_id is null or user_id = (select auth.uid()))
  );

-- 조회: 본인 구독 또는 관리자. (본인/관리자 정책을 하나로 합쳐 중복 정책 경고 방지)
drop policy if exists "subscriptions_select_own_or_admin" on public.subscriptions;
create policy "subscriptions_select_own_or_admin"
  on public.subscriptions
  for select
  to authenticated
  using (
    (user_id is not null and user_id = (select auth.uid()))
    or (select private.is_admin())
  );

-- 관리: 관리자만 구독 상태·해지 시각을 바꿀 수 있습니다.
drop policy if exists "subscriptions_update_admin" on public.subscriptions;
create policy "subscriptions_update_admin"
  on public.subscriptions
  for update
  to authenticated
  using ((select private.is_admin()))
  with check ((select private.is_admin()));

commit;

