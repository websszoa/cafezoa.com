-- 실행 순서 (supabase-function.sql 다음에 실행하세요)
--   1. supabase-profile.sql
--   2. supabase-profile-info.sql
--   3. supabase-function.sql   ← private.is_admin(), private.set_updated_at() 사용
--   4. supabase-support.sql    (현재 파일)
--
-- 대응 화면: /support (components/page/page-support.tsx)
--   - 문의 유형: inquiry(문의사항), correction(수정요청),
--               complaint(불편신고), registration(등록문의)  ← lib/support.ts
--   - 입력 항목: 이름, 이메일, 제목, 관련 주소(선택), 내용, 개인정보 수집 동의
--               ← lib/validations.ts의 supportFormSchema와 같은 규칙
--
-- 보안 원칙
--   - RLS(Row Level Security)를 항상 활성화합니다.
--   - 로그인하지 않은 방문자(anon)도 문의를 남길 수 있도록 INSERT만 허용합니다.
--     입력 가능한 컬럼만 권한을 주고, 처리 상태·관리자 메모는 입력할 수 없습니다.
--   - 접수된 문의는 관리자만 조회·처리합니다. 로그인 사용자는 본인 문의만 조회합니다.
--   - anon에게는 SELECT 권한이 없으므로, 클라이언트에서 insert 후 .select()로
--     결과를 다시 읽지 마세요. (권한 오류) 접수 성공 여부만 확인하면 됩니다.
--   - 삭제(DELETE)는 정책을 두지 않아 service_role(서버)에서만 가능합니다.
--
-- Supabase Advisor 경고 방지
--   - 정책 안의 auth.uid()는 (select auth.uid())로 감싸 행마다 재실행되지 않게 합니다.
--   - 같은 역할·동작에 permissive 정책을 하나만 둡니다. (중복 정책 경고 방지)
--   - INSERT 정책은 true가 아닌 실제 조건을 검사합니다. (항상 참 정책 경고 방지)
--   - 외래 키(user_id)에는 인덱스를 둡니다. (외래 키 인덱스 누락 경고 방지)
--   - 새 함수를 만들지 않고 supabase-function.sql의 함수를 재사용합니다.
-- =============================================================================

begin;

-- -----------------------------------------------------------------------------
-- 1. 문의 유형과 처리 상태
-- -----------------------------------------------------------------------------
-- 문의 유형. lib/support.ts의 supportTypes 키와 같아야 합니다. (default 제외)
do $$
begin
  create type public.support_type as enum (
    'inquiry',      -- 문의사항
    'correction',   -- 수정요청 (카페 정보 수정)
    'complaint',    -- 불편신고
    'registration'  -- 등록문의 (카페 등록 요청)
  );
exception
  when duplicate_object then null;
end
$$;

-- 처리 상태. 접수 시 항상 pending이며 관리자만 바꿀 수 있습니다.
do $$
begin
  create type public.support_status as enum (
    'pending',      -- 접수됨 (확인 전)
    'in_progress',  -- 확인·처리 중
    'resolved',     -- 처리 완료 (답변 발송)
    'closed'        -- 종료 (스팸, 중복 등)
  );
exception
  when duplicate_object then null;
end
$$;

-- -----------------------------------------------------------------------------
-- 2. 문의 테이블
-- -----------------------------------------------------------------------------
create table if not exists public.support_requests (
  id bigint generated by default as identity primary key,

  type public.support_type not null,
  status public.support_status not null default 'pending',

  -- 로그인 상태에서 남긴 문의만 작성자와 연결합니다. 비로그인 문의는 null.
  -- 회원 탈퇴(프로필 삭제) 시에도 문의 기록은 남기고 연결만 끊습니다.
  user_id uuid references public.profiles (id) on delete set null,

  -- 폼 입력값 (lib/validations.ts supportFormSchema와 같은 검증 + 길이 상한)
  name text not null
    check (char_length(btrim(name)) between 1 and 50),
  email text not null
    check (
      char_length(email) <= 254
      and email ~ '^[^@[:space:]]+@[^@[:space:]]+\.[^@[:space:]]+$'
    ),
  subject text not null
    check (char_length(btrim(subject)) between 1 and 200),
  related_url text
    check (
      related_url is null
      or (char_length(related_url) <= 2000 and related_url ~* '^https?://')
    ),
  content text not null
    check (char_length(btrim(content)) between 10 and 5000),

  -- 개인정보 수집·이용 동의. 동의하지 않은 문의는 저장되지 않습니다.
  privacy_consent boolean not null check (privacy_consent = true),
  privacy_consented_at timestamptz not null default now(),

  -- 관리자 처리 정보 (방문자는 입력할 수 없음)
  admin_memo text check (admin_memo is null or char_length(admin_memo) <= 5000),
  answered_at timestamptz,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

comment on table public.support_requests is
  '고객지원 문의(문의사항·수정요청·불편신고·등록문의) 접수 내역';
comment on column public.support_requests.type is
  '문의 유형. lib/support.ts의 supportTypes 키와 동일';
comment on column public.support_requests.status is
  '처리 상태. 접수 시 pending, 관리자만 변경';
comment on column public.support_requests.user_id is
  '로그인 상태에서 남긴 문의의 작성자. 비로그인 문의는 null';
comment on column public.support_requests.name is '작성자 이름';
comment on column public.support_requests.email is '답변 받을 이메일';
comment on column public.support_requests.subject is '문의 제목';
comment on column public.support_requests.related_url is
  '관련 페이지 주소(선택). http(s)로 시작';
comment on column public.support_requests.content is '문의 내용(10자 이상)';
comment on column public.support_requests.privacy_consent is
  '개인정보 수집·이용 동의 여부. 항상 true';
comment on column public.support_requests.privacy_consented_at is
  '동의 시각(DB 기록 시각)';
comment on column public.support_requests.admin_memo is
  '관리자 처리 메모. 작성자에게 보이지 않도록 클라이언트 조회 시 제외 권장';
comment on column public.support_requests.answered_at is '답변 발송 시각';

-- 외래 키 인덱스 (본인 문의 조회, 회원 삭제 시 연결 해제에 사용)
create index if not exists support_requests_user_id_idx
  on public.support_requests (user_id);

-- -----------------------------------------------------------------------------
-- 3. updated_at 자동 갱신 (supabase-function.sql의 함수 재사용)
-- -----------------------------------------------------------------------------
drop trigger if exists support_requests_set_updated_at on public.support_requests;
create trigger support_requests_set_updated_at
before update on public.support_requests
for each row
execute function private.set_updated_at();

-- -----------------------------------------------------------------------------
-- 4. 권한 (컬럼 단위 최소 권한)
-- -----------------------------------------------------------------------------
alter table public.support_requests enable row level security;

revoke all on table public.support_requests from anon, authenticated;
revoke all on sequence public.support_requests_id_seq from anon, authenticated;

-- 방문자·회원: 폼 입력 컬럼만 INSERT 가능
-- (status, admin_memo, answered_at, 시각 컬럼은 기본값으로만 채워집니다)
grant insert (
  type,
  user_id,
  name,
  email,
  subject,
  related_url,
  content,
  privacy_consent
) on table public.support_requests to anon, authenticated;

-- 회원: 본인 문의 조회 / 관리자: 전체 조회 (행 범위는 아래 RLS 정책이 제한)
grant select on table public.support_requests to authenticated;

-- 관리자 처리용 컬럼만 UPDATE 가능 (관리자 여부는 아래 RLS 정책이 확인)
grant update (status, admin_memo, answered_at)
  on table public.support_requests to authenticated;

-- -----------------------------------------------------------------------------
-- 5. RLS 정책
-- -----------------------------------------------------------------------------
-- 접수: 비로그인은 user_id 없이, 로그인은 본인 user_id로만 남길 수 있습니다.
-- 접수 상태는 항상 pending이어야 합니다. (다른 상태로 위장 접수 방지)
drop policy if exists "support_requests_insert_anyone" on public.support_requests;
create policy "support_requests_insert_anyone"
  on public.support_requests
  for insert
  to anon, authenticated
  with check (
    status = 'pending'
    and privacy_consent = true
    and (user_id is null or user_id = (select auth.uid()))
  );

-- 조회: 본인 문의 또는 관리자. (본인/관리자 정책을 하나로 합쳐 중복 정책 경고 방지)
drop policy if exists "support_requests_select_own_or_admin" on public.support_requests;
create policy "support_requests_select_own_or_admin"
  on public.support_requests
  for select
  to authenticated
  using (
    (user_id is not null and user_id = (select auth.uid()))
    or (select private.is_admin())
  );

-- 처리: 관리자만 상태·메모·답변 시각을 바꿀 수 있습니다.
drop policy if exists "support_requests_update_admin" on public.support_requests;
create policy "support_requests_update_admin"
  on public.support_requests
  for update
  to authenticated
  using ((select private.is_admin()))
  with check ((select private.is_admin()));

commit;

