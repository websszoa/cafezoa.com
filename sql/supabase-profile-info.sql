-- =============================================================================
-- Cafezoa 사용자 접속 정보 스키마 (최소 필수 항목)
--
-- 선행 파일: supabase-profile.sql
-- 후속 파일: supabase-function.sql
--
-- 한 사용자에게 여러 번의 로그인/방문이 있을 수 있으므로 1:N 구조이며,
-- 수정 없이 로그인마다 새 행을 추가하는 이력(log) 테이블입니다.
--
-- 저장 항목: IP, 위치(국가/지역/도시), 위도/경도,
--          브라우저/OS/디바이스 종류, 리퍼러(유입 경로)
--
-- 보안 원칙
--   - 이 테이블의 모든 값은 클라이언트가 직접 보낸 값을 신뢰하지 않고,
--     서버(Route Handler/Edge Function)가 요청 헤더에서 추출하여
--     service_role 키로만 기록합니다. 그래서 authenticated 역할에는
--     insert/update 권한을 주지 않습니다(자기 위치/IP 조작 방지).
--   - 조회는 본인 또는 관리자만 가능합니다. 관리자 조회 정책은
--     supabase-function.sql에서 추가합니다.
-- =============================================================================

begin;

create table if not exists public.profile_info (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles (id) on delete cascade,

  -- 네트워크/위치 정보: 반드시 서버에서 요청을 검증한 뒤 기록하세요.
  ip inet,
  country text,
  region text,
  city text,
  latitude numeric(9, 6) check (latitude between -90 and 90),
  longitude numeric(9, 6) check (longitude between -180 and 180),

  -- 브라우저/기기 정보: User-Agent를 서버에서 파싱한 결과만 저장합니다.
  browser text,
  operating_system text,
  device_type text,

  -- 유입 경로. HTTP 헤더 이름을 그대로 따라 referer로 표기합니다.
  referer text,

  created_at timestamptz not null default now()
);

comment on table public.profile_info is
  '사용자 로그인/방문 시점의 IP, 위치, 기기, 유입 경로 이력(수정 없는 로그)';
comment on column public.profile_info.ip is
  '서버 요청 헤더에서 추출한 접속 IP. 클라이언트 입력값 사용 금지';
comment on column public.profile_info.country is 'IP 기반으로 조회한 국가';
comment on column public.profile_info.region is 'IP 기반으로 조회한 지역(시/도)';
comment on column public.profile_info.city is 'IP 기반으로 조회한 도시';
comment on column public.profile_info.browser is '서버에서 파싱한 브라우저 이름/버전';
comment on column public.profile_info.operating_system is '서버에서 파싱한 OS 이름/버전';
comment on column public.profile_info.device_type is '예: desktop, mobile, tablet, ipad';
comment on column public.profile_info.referer is 'HTTP Referer 헤더(유입 경로)';

-- user_id로 본인/관리자 조회를 자주 하므로 조회 성능을 위한 인덱스를 둡니다.
create index if not exists profile_info_user_id_idx
  on public.profile_info (user_id);

alter table public.profile_info enable row level security;

-- authenticated에게는 조회 권한만 부여합니다.
-- insert/update는 service_role(서버)에서만 수행하므로 여기서 권한을 주지 않습니다.
revoke all on table public.profile_info from anon, authenticated;
revoke all on sequence public.profile_info_id_seq from anon, authenticated;
grant select on table public.profile_info to authenticated;

-- 함수 SQL을 재적용하기 전에는 본인 조회 정책만 유지합니다.
-- 기존 통합 정책이 있으면 제거하여 SELECT 정책 중복을 방지합니다.
drop policy if exists "profile_info_select_admin" on public.profile_info;
drop policy if exists "profile_info_select_own_or_admin" on public.profile_info;
drop policy if exists "profile_info_select_own" on public.profile_info;
create policy "profile_info_select_own"
  on public.profile_info
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

commit;
